/**
 * The Patrol iOS lane on simulators.
 *
 * Patrol runs iOS tests through an XCUITest target named `RunnerUITests`
 * (https://patrol.leancode.co/documentation, iOS setup). `flutter create`
 * never generates it, and without it `patrol test` cannot build, so SaySpec
 * previews the exact project changes the way it does for Android.
 */

const PROJECT = 'ios/Runner.xcodeproj/project.pbxproj';
const SCHEME = 'ios/Runner.xcodeproj/xcshareddata/xcschemes/Runner.xcscheme';
const RUNNER_SOURCE = 'ios/RunnerUITests/RunnerUITests.m';
const PODFILE = 'ios/Podfile';

/** Files of the iOS wiring. They only work together, so they are applied as one unit. */
export const IOS_PATROL_FILES: readonly string[] = [PROJECT, SCHEME, RUNNER_SOURCE, PODFILE];

/** The id `flutter`, `patrol` and `simctl` use for a listed device. */
export function flutterDeviceId(device: Pick<FlutterDeviceSummary, 'id' | 'name'>) {
  if (device.id.startsWith('avd:')) return device.name;
  if (device.id.startsWith('ios:')) return device.id.slice('ios:'.length);
  return device.id;
}

/** `iOS 26.5` → `26.5`, the value `patrol test --ios` puts in the xcodebuild destination. */
export function simulatorOsVersion(device: Pick<FlutterDeviceSummary, 'runtime'>) {
  return /(\d+(?:\.\d+)*)/.exec(device.runtime ?? '')?.[1];
}

const RUNNER_UI_TESTS_SOURCE = `@import XCTest;
@import patrol;
@import ObjectiveC.runtime;

// Generated by SaySpec for Patrol. Required so \`patrol test\` can run the Dart
// tests on iOS; see https://patrol.leancode.co for the upstream contract.
PATROL_INTEGRATION_TEST_IOS_RUNNER(RunnerUITests)
`;

/**
 * Adds the RunnerUITests target with the settings from Patrol's iOS guide and
 * its example app. UUIDs derive from the current project file, so the preview
 * and the apply that re-creates it write the same text.
 */
const ADD_TARGET_SCRIPT = String.raw`
require 'digest'
require 'json'
require 'xcodeproj'

project_path = ARGV.fetch(0)
seed = Digest::SHA256.hexdigest(File.read(File.join(project_path, 'project.pbxproj')))
project = Xcodeproj::Project.open(project_path)
counter = 0
project.define_singleton_method(:generate_uuid) do
  loop do
    counter += 1
    uuid = Digest::SHA256.hexdigest("#{seed}:#{counter}")[0, 24].upcase
    return uuid unless objects_by_uuid.key?(uuid)
  end
end

runner = project.native_targets.find { |target| target.name == 'Runner' }
abort 'The Xcode project has no Runner target.' unless runner
existing = project.native_targets.find { |target| target.name == 'RunnerUITests' }
if existing
  puts JSON.generate({ changed: false, targetId: existing.uuid })
  exit 0
end

runner_configs = runner.build_configurations.to_h { |config| [config.name, config] }
deployment = runner.build_configurations.map { |config| config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] }.compact.first ||
  project.build_configurations.map { |config| config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] }.compact.first || '13.0'

target = project.new_target(:ui_test_bundle, 'RunnerUITests', :ios, deployment, nil, :objc)
target.build_configurations.each do |config|
  runner_config = runner_configs[config.name] || runner_configs['Debug']
  source = runner_config ? runner_config.build_settings : {}
  # The Runner's Flutter xcconfig includes Generated.xcconfig (FLUTTER_ROOT,
  # FLUTTER_BUILD_DIR), which the xcode_backend phases below need.
  config.base_configuration_reference = runner_config.base_configuration_reference if runner_config && runner_config.base_configuration_reference
  bundle = source['PRODUCT_BUNDLE_IDENTIFIER'] || 'com.example.app'
  settings = config.build_settings
  settings['PRODUCT_NAME'] = '$(TARGET_NAME)'
  settings['PRODUCT_BUNDLE_IDENTIFIER'] = "#{bundle}.RunnerUITests"
  settings['TEST_TARGET_NAME'] = 'Runner'
  settings['IPHONEOS_DEPLOYMENT_TARGET'] = deployment
  settings['GENERATE_INFOPLIST_FILE'] = 'YES'
  settings['ENABLE_USER_SCRIPT_SANDBOXING'] = 'NO'
  settings['CODE_SIGN_STYLE'] = 'Automatic'
  settings['CURRENT_PROJECT_VERSION'] = '1'
  settings['MARKETING_VERSION'] = '1.0'
  settings['TARGETED_DEVICE_FAMILY'] = '1,2'
  settings['DEVELOPMENT_TEAM'] = source['DEVELOPMENT_TEAM'] if source['DEVELOPMENT_TEAM']
end
target.add_dependency(runner)

# new_target links Foundation from a hard-coded SDK path; the runner needs none of it.
target.frameworks_build_phase.files.to_a.each do |build_file|
  reference = build_file.file_ref
  build_file.remove_from_project
  reference.remove_from_project if reference && reference.build_files.empty?
end
frameworks = project.main_group.children.find { |child| child.display_name == 'Frameworks' && child.respond_to?(:groups) }
if frameworks
  frameworks.groups.select { |group| group.display_name == 'iOS' && group.children.empty? }.each(&:remove_from_project)
  frameworks.remove_from_project if frameworks.children.empty?
end

# A Swift Package Manager project links its plugins through this product.
runner.package_product_dependencies.select { |dependency| dependency.product_name == 'FlutterGeneratedPluginSwiftPackage' }.each do |dependency|
  copy = project.new(Xcodeproj::Project::Object::XCSwiftPackageProductDependency)
  copy.product_name = dependency.product_name
  copy.package = dependency.package if dependency.package
  target.package_product_dependencies << copy
end

group = project.main_group.find_subpath('RunnerUITests', false) || project.main_group.new_group('RunnerUITests', 'RunnerUITests')
file = group.files.find { |reference| reference.path == 'RunnerUITests.m' } || group.new_reference('RunnerUITests.m')
target.add_file_references([file])

# Build the Flutter app before compiling the runner and embed it after, on
# every build rather than only for install builds.
backend = '/bin/sh "$FLUTTER_ROOT/packages/flutter_tools/bin/xcode_backend.sh"'
build = target.new_shell_script_build_phase('xcode_backend build')
build.shell_script = "#{backend} build\n"
build.always_out_of_date = '1'
target.build_phases.delete(build)
target.build_phases.unshift(build)
embed = target.new_shell_script_build_phase('xcode_backend embed_and_thin')
embed.shell_script = "#{backend} embed_and_thin\n"
embed.always_out_of_date = '1'

attributes = project.root_object.attributes['TargetAttributes'] ||= {}
attributes[target.uuid] = { 'CreatedOnToolsVersion' => '15.0', 'TestTargetID' => runner.uuid }

project.save
puts JSON.generate({ changed: true, targetId: target.uuid })
`;

type PreviewFile = FlutterIntegrationPreview['files'][number];

/** Builds the Patrol iOS wiring as reviewable file changes. */
export async function previewPatrolIosConfig(sourcePath: string): Promise<{ files: PreviewFile[]; notes: string[] }> {
  const files: PreviewFile[] = [];
  const notes: string[] = [];
  const pbxproj = await readText(path.join(sourcePath, PROJECT));
  if (!pbxproj) {
    notes.push('No ios/Runner.xcodeproj was found, so Patrol cannot be wired for iOS. Create the iOS platform first (`flutter create --platforms=ios .`).');
    return { files, notes };
  }
  const wiring = await readIosPatrolWiring(sourcePath);
  if (wiring.ready) {
    notes.push('The iOS Patrol test target is already present.');
    return { files, notes };
  }

  let targetId = existingUiTestTargetId(pbxproj);
  if (!targetId) {
    const added = await addRunnerUiTestsTarget(sourcePath);
    if ('error' in added) {
      notes.push(`SaySpec could not prepare the iOS Patrol target: ${added.error} Follow Patrol's iOS setup guide in Xcode (add a RunnerUITests UI Testing Bundle target), then check again.`);
      return { files, notes };
    }
    targetId = added.targetId;
    files.push({
      relativePath: PROJECT,
      baseSha256: sha(pbxproj),
      description: 'Adds the RunnerUITests UI test target Patrol runs iOS tests through: it depends on Runner, reuses Runner\'s Flutter build configuration, and builds and embeds the Flutter app before each test build. Without it, `patrol test` cannot build for iOS.',
      proposedText: added.text,
    });
  }

  const scheme = await readText(path.join(sourcePath, SCHEME));
  if (scheme && !scheme.includes('BuildableName = "RunnerUITests.xctest"')) {
    if (!scheme.includes('</Testables>')) notes.push(`${SCHEME} has no Testables list; add RunnerUITests to the Runner scheme's Test action in Xcode.`);
    else files.push({
      relativePath: SCHEME,
      baseSha256: sha(scheme),
      description: 'Adds RunnerUITests to the Runner scheme\'s tests, because `patrol test` builds the tests of that scheme.',
      proposedText: scheme.replace('      </Testables>', `${testableReference(targetId)}      </Testables>`),
    });
  } else if (!scheme) notes.push(`${SCHEME} is missing; Xcode recreates it when the project is opened, then check again.`);

  const runnerSource = await readText(path.join(sourcePath, RUNNER_SOURCE));
  if (!runnerSource?.includes('PATROL_INTEGRATION_TEST_IOS_RUNNER')) {
    files.push({
      relativePath: RUNNER_SOURCE,
      ...(runnerSource === undefined ? {} : { baseSha256: sha(runnerSource) }),
      description: 'The XCUITest entry point that lists the Dart tests and runs each one inside the app.',
      proposedText: RUNNER_UI_TESTS_SOURCE,
    });
  }

  const podfile = await readText(path.join(sourcePath, PODFILE));
  if (podfile && !/target\s+['"]RunnerUITests['"]/.test(podfile)) {
    const patched = patchPodfile(podfile);
    if (patched) files.push({
      relativePath: PODFILE,
      baseSha256: sha(podfile),
      description: 'Gives RunnerUITests the app\'s pods, including Patrol\'s native part, so the runner can link it.',
      proposedText: patched,
    });
    else notes.push('ios/Podfile has no `target \'Runner\' do` block; add `target \'RunnerUITests\' do inherit! :complete end` inside it by hand.');
  }
  if (files.length) notes.push('The iOS files only work together, so they are applied as one change. CocoaPods runs during the next iOS build.');
  return { files, notes };
}

function existingUiTestTargetId(pbxproj: string) {
  return /^\s*([0-9A-F]{24}) \/\* RunnerUITests \*\/ = \{\s*\n\s*isa = PBXNativeTarget;/m.exec(pbxproj)?.[1];
}

function testableReference(targetId: string) {
  return `         <TestableReference
            skipped = "NO"
            parallelizable = "NO">
            <BuildableReference
               BuildableIdentifier = "primary"
               BlueprintIdentifier = "${targetId}"
               BuildableName = "RunnerUITests.xctest"
               BlueprintName = "RunnerUITests"
               ReferencedContainer = "container:Runner.xcodeproj">
            </BuildableReference>
         </TestableReference>
`;
}

/** Nests the RunnerUITests pods target in the Runner target, as Patrol's guide shows. */
export function patchPodfile(podfile: string) {
  const lines = podfile.split('\n');
  const start = lines.findIndex((line) => /^target\s+['"]Runner['"]\s+do\b/.test(line));
  if (start < 0) return undefined;
  const end = lines.findIndex((line, index) => index > start && /^end\b/.test(line));
  if (end < 0) return undefined;
  lines.splice(end, 0, '', "  target 'RunnerUITests' do", '    inherit! :complete', '  end');
  return lines.join('\n');
}

/**
 * Runs the target script on a copy of the Xcode project, so nothing in the
 * selected source changes until the user applies the preview.
 */
async function addRunnerUiTestsTarget(sourcePath: string): Promise<{ text: string; targetId: string } | { error: string }> {
  const work = await mkdtemp(path.join(tmpdir(), 'sayspec-xcodeproj-'));
  try {
    const project = path.join(work, 'Runner.xcodeproj');
    await cp(path.join(sourcePath, 'ios', 'Runner.xcodeproj'), project, { recursive: true });
    const script = path.join(work, 'add_runner_ui_tests.rb');
    await writeFile(script, ADD_TARGET_SCRIPT);
    let failure = 'no Ruby with the xcodeproj gem (installed with CocoaPods) was found.';
    for (const ruby of await xcodeprojRubies()) {
      const result = await runFile(ruby.path, [script, project], { timeoutMs: 60_000, env: { ...process.env, ...ruby.env } });
      if (result.code !== 0) {
        if (/cannot load such file -- xcodeproj|LoadError/.test(result.stderr)) continue;
        failure = result.stderr.trim().split('\n').at(-1) || `ruby exited with code ${result.code}.`;
        break;
      }
      const targetId = (JSON.parse(result.stdout.trim().split('\n').at(-1) ?? '{}') as { targetId?: string }).targetId;
      if (!targetId) return { error: 'the target script reported no target.' };
      return { text: await readFile(path.join(project, 'project.pbxproj'), 'utf8'), targetId };
    }
    return { error: failure };
  } catch (error) {
    return { error: error instanceof Error ? error.message : String(error) };
  } finally {
    await rm(work, { recursive: true, force: true });
  }
}

/**
 * Rubies that can load `xcodeproj`, the gem CocoaPods edits Xcode projects
 * with. A Homebrew CocoaPods keeps its gems in a private GEM_HOME named by its
 * `pod` wrapper, so that one is tried first.
 */
async function xcodeprojRubies() {
  const candidates: { path: string; env: Record<string, string> }[] = [];
  const pod = await resolveTool({ name: 'pod', skipVersion: true });
  if (pod.found && pod.path) {
    const wrapper = await readText(pod.path) ?? '';
    const wrapped = /GEM_HOME="([^"]+)"\s+exec\s+"([^"]+)"/.exec(wrapper);
    const script = wrapped?.[2] ?? pod.path;
    const shebang = /^#!\s*(\S+)/.exec(await readText(script) ?? '')?.[1];
    if (shebang && !shebang.endsWith('/env') && !shebang.endsWith('/bash') && !shebang.endsWith('/sh')) {
      candidates.push({ path: shebang, env: wrapped ? { GEM_HOME: wrapped[1]! } : {} });
    }
  }
  candidates.push({ path: '/usr/bin/ruby', env: {} });
  const ruby = await resolveTool({ name: 'ruby', skipVersion: true });
  if (ruby.found && ruby.path) candidates.push({ path: ruby.path, env: {} });
  return candidates.filter((candidate, index) => candidates.findIndex((other) => other.path === candidate.path && JSON.stringify(other.env) === JSON.stringify(candidate.env)) === index);
}

/**
 * Confirms the project can run Patrol tests on iOS: the UI test target, its
 * runner source, the scheme entry and the pods target all exist.
 */
export async function readIosPatrolWiring(sourcePath: string) {
  const pbxproj = await readText(path.join(sourcePath, PROJECT));
  if (!pbxproj) return { ready: false, detail: 'The project has no ios/Runner.xcodeproj. Create the iOS platform before running Patrol tests on a simulator.' };
  const action = 'Apply the Patrol iOS integration in Settings or from the recording review.';
  if (!existingUiTestTargetId(pbxproj)) return { ready: false, detail: `The Xcode project has no RunnerUITests target, so \`patrol test\` cannot build for iOS. ${action}` };
  const runner = await readText(path.join(sourcePath, RUNNER_SOURCE));
  if (!runner?.includes('PATROL_INTEGRATION_TEST_IOS_RUNNER')) return { ready: false, detail: `${RUNNER_SOURCE} does not declare Patrol's test runner, so no Dart test would be listed. ${action}` };
  const scheme = await readText(path.join(sourcePath, SCHEME));
  if (scheme && !scheme.includes('BuildableName = "RunnerUITests.xctest"')) return { ready: false, detail: `The Runner scheme does not test RunnerUITests, so \`patrol test\` would build no test runner. ${action}` };
  const podfile = await readText(path.join(sourcePath, PODFILE));
  if (podfile && !/target\s+['"]RunnerUITests['"]/.test(podfile)) return { ready: false, detail: `ios/Podfile does not give RunnerUITests the app's pods, so the runner cannot link Patrol. ${action}` };
  return { ready: true, detail: 'The iOS Patrol test target is configured.' };
}

/** Where a previous run's result bundles live; they are removed before a run. */
export async function removeXcresults(sourcePath: string) {
  const build = path.join(sourcePath, 'build');
  for (const entry of await readdir(build).catch(() => [])) {
    if (/^ios_results_\d+\.xcresult$/.test(entry)) await rm(path.join(build, entry), { recursive: true, force: true });
  }
}

interface XcresultNode { name?: string; nodeType?: string; result?: string; durationInSeconds?: number; children?: XcresultNode[] }

/**
 * Every test case in the latest `.xcresult` bundle Patrol wrote, the iOS
 * counterpart of Gradle's JUnit XML. Titles use the Dart test name
 * (`<bundle name> <test>`), which Patrol encodes into the XCTest selector.
 */
export async function readXcresultCases(sourcePath: string): Promise<{ tests: PatrolTestOutcome[]; json?: string }> {
  const build = path.join(sourcePath, 'build');
  const bundles = (await readdir(build).catch(() => [])).filter((entry) => /^ios_results_\d+\.xcresult$/.test(entry)).sort();
  const latest = bundles.at(-1);
  if (!latest) return { tests: [] };
  const result = await runFile('/usr/bin/xcrun', ['xcresulttool', 'get', 'test-results', 'tests', '--path', path.join(build, latest)], { timeoutMs: 60_000 });
  if (result.code !== 0) return { tests: [] };
  let parsed: { testNodes?: XcresultNode[] };
  try { parsed = JSON.parse(result.stdout) as { testNodes?: XcresultNode[] }; } catch { return { tests: [] }; }
  return { tests: xcresultCases(parsed.testNodes ?? []), json: result.stdout };
}

export function xcresultCases(nodes: readonly XcresultNode[]): PatrolTestOutcome[] {
  const tests: PatrolTestOutcome[] = [];
  const walk = (node: XcresultNode) => {
    if (node.nodeType === 'Test Case' && node.name) {
      const failures = (node.children ?? []).filter((child) => child.nodeType === 'Failure Message' && child.name).map((child) => child.name!.slice(0, 4_000));
      const outcome = node.result === 'Passed' ? 'passed' : node.result === 'Skipped' || node.result === 'Expected Failure' ? 'skipped' : 'failed';
      tests.push({ id: `xcresult:${node.name}`, title: dartTestName(node.name), outcome, durationMs: Math.round((node.durationInSeconds ?? 0) * 1_000), errors: outcome === 'failed' ? failures : [] });
      return;
    }
    for (const child of node.children ?? []) walk(child);
  };
  for (const node of nodes) walk(node);
  return tests;
}

/** Inverts Patrol's selector encoding: `+` → space, then `__PLUS__` → `+`. */
export function dartTestName(selector: string) {
  return selector.replaceAll('+', ' ').replaceAll('__PLUS__', '+');
}

/**
 * Bundle ids the Runner target builds, the launched configuration first.
 * Test targets and unresolved build-setting references are skipped.
 */
export async function xcodeBundleIds(sourcePath: string, flavor?: string) {
  const pbxproj = await readText(path.join(sourcePath, PROJECT)) ?? '';
  const wanted = flavor ? `Debug-${flavor}` : 'Debug';
  const preferred: string[] = [];
  const others: string[] = [];
  for (const match of pbxproj.matchAll(/isa = XCBuildConfiguration;[\s\S]*?buildSettings = \{([\s\S]*?)\n\t\t\t\};\n\t\t\tname = "?([^";]+)"?;/g)) {
    const id = /PRODUCT_BUNDLE_IDENTIFIER = "?([^";]+)"?;/.exec(match[1]!)?.[1];
    if (!id || id.includes('$(') || /\.Runner(UI)?Tests$/.test(id)) continue;
    (match[2] === wanted ? preferred : others).push(id);
  }
  return [...new Set([...preferred, ...others])];
}

/** True when the app with this bundle id is installed on the simulator. */
export async function simulatorHasApp(udid: string, bundleId: string) {
  const result = await runFile('/usr/bin/xcrun', ['simctl', 'get_app_container', udid, bundleId], { timeoutMs: 15_000 });
  return result.code === 0;
}

async function readText(candidate: string) {
  try { return await readFile(candidate, 'utf8'); } catch { return undefined; }
}

function sha(value: string) { return createHash('sha256').update(value).digest('hex'); }
